// Samples real source files for the corpus at random, stratified by language, test vs. source, and size,
// from permissively licensed GitHub repos at their current default-branch commit. For each pick it records
// the date of the last commit that touched the file (H8: prefer code written after Clef's training data)
// and saves the bytes. Raw API answers are cached, so reruns with the same seed pick the same files.
//   bun evals/sample.ts [--per-repo 4] [--test-share 0.3] [--seed 1] <owner/repo> ...
// Output: evals/.cache/research/sample/candidates.jsonl (one line per picked file) and files/<repo>/<sha>/<path>.
import { existsSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { $ } from "bun"

const out = join(import.meta.dir, ".cache/research/sample")
const candidatesPath = join(out, "candidates.jsonl")
const rateReserve = 100
const maxBytes = 60_000

const args = Bun.argv.slice(2)
const option = (name: string, fallback: number) => {
  const index = args.indexOf(name)
  if (index === -1) return fallback
  const value = Number(args[index + 1])
  args.splice(index, 2)
  return value
}
const perRepo = option("--per-repo", 4)
const testShare = option("--test-share", 0.3)
const seed = option("--seed", 1)
const repos = args
if (repos.length === 0 || !Number.isInteger(perRepo) || perRepo < 1 || !(0 <= testShare && testShare <= 1)) {
  console.error("usage: bun evals/sample.ts [--per-repo N] [--test-share 0..1] [--seed N] <owner/repo> ...")
  process.exit(1)
}

const licenses = new Set(["MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "0BSD"])
const languageOf = (path: string) =>
  /\.go$/.test(path) ? "go" : /\.py$/.test(path) ? "py" : /\.tsx?$/.test(path) && !/\.d\.ts$/.test(path) ? "ts" : undefined
// Vendored, generated, built, fixture, example and migration code isn't what users lint.
const excluded =
  /(^|\/)(vendor|node_modules|third_party|dist|build|out|generated|__generated__|fixtures?|testdata|examples?|samples?|migrations|docs?)\/|_generated|\.pb\.go$|_pb2\.py$|zz_generated|\.min\.|(^|\/)setup\.py$|(^|\/)conftest\.py$|__init__\.py$/
const isTest = (path: string) =>
  /(_test\.go|(^|\/)test_[^/]*\.py|_test\.py|\.(test|spec)\.tsx?)$/.test(path) || /(^|\/)(tests?|__tests__)\//.test(path)
const sizeBin = (bytes: number) => (bytes < 4_000 ? "<4KB" : bytes < 9_000 ? "4-9KB" : ">9KB")
const generatedMarker = /Code generated .* DO NOT EDIT|@generated|autogenerated|auto-generated/i

// Mulberry32: a small seeded generator, so a seed always picks the same files from the same trees.
const random = (state: number) => () => {
  state = (state + 0x6d2b79f5) | 0
  let t = Math.imul(state ^ (state >>> 15), 1 | state)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const shuffle = <A>(items: Array<A>, next: () => number) => {
  for (let i = items.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1))
    ;[items[i], items[j]] = [items[j]!, items[i]!]
  }
  return items
}
const hash = (text: string) => [...text].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) | 0, seed)

let remaining = (await $`gh api rate_limit --jq .resources.core.remaining`.json()) as number
const cached = async <A>(file: string, path: string, jq?: string): Promise<A | undefined> => {
  const cache = Bun.file(file)
  if (await cache.exists()) return (await cache.json()) as A
  if (remaining <= rateReserve) return undefined
  remaining -= 1
  const result = jq === undefined ? await $`gh api ${path}`.nothrow().quiet() : await $`gh api ${path} --jq ${jq}`.nothrow().quiet()
  if (result.exitCode !== 0) return undefined
  const value = result.json() as A
  await Bun.write(file, JSON.stringify(value))
  return value
}

type Entry = { path: string; type: string; size?: number }
mkdirSync(out, { recursive: true })
const taken = new Set<string>()
if (existsSync(candidatesPath)) {
  for (const line of (await Bun.file(candidatesPath).text()).split("\n")) {
    if (line !== "") taken.add((JSON.parse(line) as { repo: string }).repo)
  }
}

const lines: Array<string> = []
for (const repo of repos) {
  if (taken.has(repo)) continue
  const raw = join(out, "raw", repo.replace("/", "__"))
  mkdirSync(raw, { recursive: true })
  const info = await cached<{ license: string | null; branch: string; stars: number; fork: boolean; archived: boolean }>(
    join(raw, "repo.json"), `repos/${repo}`,
    "{license: .license.spdx_id, branch: .default_branch, stars: .stargazers_count, fork: .fork, archived: .archived}")
  if (info === undefined || info.license === null || !licenses.has(info.license) || info.fork || info.archived) {
    console.log(`${repo}: skipped (${info === undefined ? "unavailable" : `license ${info.license}`})`)
    continue
  }
  const head = await cached<{ sha: string; date: string }>(join(raw, "head.json"), `repos/${repo}/commits/${info.branch}`,
    "{sha: .sha, date: .commit.committer.date}")
  if (head === undefined) continue
  const tree = await cached<{ entries: Array<Entry>; truncated: boolean }>(join(raw, "tree.json"),
    `repos/${repo}/git/trees/${head.sha}?recursive=1`, "{entries: [.tree[] | {path, type, size}], truncated}")
  if (tree === undefined) continue
  const pool = tree.entries.filter((entry) =>
    entry.type === "blob" && languageOf(entry.path) !== undefined && !excluded.test(entry.path) &&
    (entry.size ?? 0) >= 300 && (entry.size ?? 0) <= maxBytes)
  // Stratify within the repo: each pick is a test file with probability `testShare`, then a uniformly
  // chosen non-empty size bin, then a file, all from a generator seeded by the repo name.
  const next = random(hash(repo))
  const cells = new Map<string, Array<Entry>>()
  for (const entry of pool) {
    const key = `${isTest(entry.path) ? "test" : "source"}/${sizeBin(entry.size!)}`
    cells.set(key, [...(cells.get(key) ?? []), entry])
  }
  for (const files of cells.values()) shuffle(files.sort((a, b) => a.path.localeCompare(b.path)), next)
  const open = (kind: string) => [...cells.keys()].sort().filter((key) => key.startsWith(kind) && cells.get(key)!.length > 0)
  let picked = 0
  while (picked < perRepo && (open("test").length > 0 || open("source").length > 0)) {
    const wanted = next() < testShare ? "test" : "source"
    const keys = open(wanted).length > 0 ? open(wanted) : open(wanted === "test" ? "source" : "test")
    const key = keys[Math.floor(next() * keys.length)]!
    const entry = cells.get(key)!.shift()!
    const local = join(out, "files", repo.replace("/", "__"), head.sha, entry.path)
    if (!existsSync(local)) {
      const response = await fetch(`https://raw.githubusercontent.com/${repo}/${head.sha}/${entry.path}`)
      if (!response.ok) continue
      mkdirSync(dirname(local), { recursive: true })
      await Bun.write(local, await response.arrayBuffer())
    }
    const text = await Bun.file(local).text()
    if (generatedMarker.test(text.slice(0, 2_000))) continue
    const last = await cached<Array<{ sha: string; date: string }>>(
      join(raw, `last-${Bun.hash(entry.path).toString(16)}.json`),
      `repos/${repo}/commits?sha=${head.sha}&path=${encodeURIComponent(entry.path)}&per_page=1`,
      "[.[] | {sha: .sha, date: .commit.committer.date}]")
    if (last === undefined || last.length === 0) continue
    picked++
    lines.push(JSON.stringify({
      repo, license: info.license, stars: info.stars, commit: head.sha, headDate: head.date, path: entry.path,
      language: languageOf(entry.path), test: isTest(entry.path), bytes: entry.size, bin: sizeBin(entry.size!),
      stratum: `${languageOf(entry.path)}/${key}`, committed: last[0]!.date, lastCommit: last[0]!.sha, local,
    }))
  }
  console.log(`${repo}: ${picked} of ${pool.length} eligible files${tree.truncated ? " (tree truncated)" : ""}`)
}
if (lines.length > 0) {
  const previous = existsSync(candidatesPath) ? await Bun.file(candidatesPath).text() : ""
  await Bun.write(candidatesPath, previous + lines.map((line) => `${line}\n`).join(""))
}
console.log(`${lines.length} files sampled; ${remaining} API requests left`)
