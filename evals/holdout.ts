// Fresh H26 holdout builder: samples unseen permissively licensed real files from GitHub (excluding all
// repos already in the corpus) and labels them with the exact H11 two-model protocol (Claude + Codex
// independently, blinded Claude adjudicator on violates-vs-clean disagreements).
//   bun evals/holdout.ts --sample [--count 216] [--per-repo 3] [--seed 20261122]
//   bun evals/holdout.ts --label [--limit N] [--concurrency 4] [--claude-model <m>] [--codex-model <m>]
//   bun evals/holdout.ts --status
import { existsSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { $ } from "bun"
import { loadCorpus, ruleText } from "./corpus.ts"

const holdoutDir = join(import.meta.dir, "corpus/holdout")
const filesDir = join(holdoutDir, "files")
const manifestPath = join(holdoutDir, "manifest.jsonl")
const labeledPath = join(holdoutDir, "holdout.jsonl")
const cacheDir = join(import.meta.dir, ".cache/holdout")
const reposTsv = join(import.meta.dir, ".cache/research/sample/repos.tsv")
const licensesDir = join(import.meta.dir, "corpus/licenses")

const args = Bun.argv.slice(2)
const hasFlag = (name: string) => args.includes(name)
const opt = (name: string, fallback: string) => {
  const i = args.indexOf(name)
  return i === -1 ? fallback : (args[i + 1] ?? fallback)
}

const licenses = new Set(["MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "0BSD"])
const excluded =
  /(^|\/)(vendor|node_modules|third_party|dist|build|out|generated|__generated__|fixtures?|testdata|examples?|samples?|migrations|docs?)\/|_generated|\.pb\.go$|_pb2\.py$|zz_generated|\.min\.|(^|\/)setup\.py$|(^|\/)conftest\.py$|__init__\.py$/
const badRepo = /awesome|tutorial|course|interview|leetcode|cheat|roadmap|book|example|demo|template|boilerplate|starter|homework|exercise|learn/i
const generatedMarker = /Code generated .* DO NOT EDIT|@generated|autogenerated|auto-generated/i
const isTestPath = (path: string) =>
  /(_test\.go|(^|\/)test_[^/]*\.py|_test\.py|\.(test|spec)\.tsx?)$/.test(path) || /(^|\/)(tests?|__tests__)\//.test(path)
const langOf = (path: string): "go" | "py" | "ts" | undefined =>
  /\.go$/.test(path) ? "go" : /\.py$/.test(path) ? "py" : /\.tsx?$/.test(path) && !/\.d\.ts$/.test(path) ? "ts" : undefined
const sizeBin = (bytes: number) => (bytes < 4_000 ? "<4KB" : bytes < 9_000 ? "4-9KB" : ">9KB")

const mulberry32 = (seed: number) => () => {
  seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const shuffle = <A>(arr: Array<A>, next: () => number) => {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1))
    ;[arr[i], arr[j]] = [arr[j]!, arr[i]!]
  }
  return arr
}
const hashStr = (text: string, seed: number) => [...text].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) | 0, seed)

interface ManifestEntry {
  readonly id: string
  readonly path: string
  readonly language: "go" | "py" | "ts"
  readonly origin: "real"
  readonly upstream: { readonly repo: string; readonly commit: string; readonly path: string; readonly license: string }
  readonly provenance: { readonly source: "sampled"; readonly committed: string; readonly stratum: string; readonly stars: number }
}

const loadManifest = async (): Promise<Array<ManifestEntry>> => {
  if (!existsSync(manifestPath)) return []
  return (await Bun.file(manifestPath).text()).trim().split("\n").filter(Boolean).map((l) => JSON.parse(l) as ManifestEntry)
}

const matchingSemanticPolicies = (path: string, allSemantic: ReadonlyArray<string>) => {
  const test = isTestPath(path)
  return allSemantic.filter((name) => test || !name.startsWith("semantic/testing/"))
}

const slug = (name: string) => name.replaceAll("/", ".").replace("semantic.", "").slice(0, 64)
const numbered = (src: string) => src.split("\n").map((l, i) => `${i + 1}: ${l}`).join("\n")

// Exact H11 prompts from evals/.cache/research/pipeline.py
const LABELER_SYSTEM = `You are an expert code reviewer labeling a gold corpus for a semantic linter. For each rule you are given, decide whether the file violates it.

Labels:
- "violates": the file clearly contains at least one violation of the rule as written (respecting its stated exemptions).
- "complies": the rule governs something in the file and the file follows it.
- "not-applicable": the rule governs nothing in this file (e.g. an error-handling rule in a file that handles no errors).

Judge each rule independently and strictly by its text. Do not flag style preferences the rule does not state. For "violates", give the 1-based inclusive line ranges of the violations and a one-sentence note naming the offending code. For other labels, give a one-sentence note.`

const ADJ_SYSTEM = `You adjudicate a disagreement between two code reviewers about whether a file violates a rule. Read the rule (including its exemptions), the cited lines, and both arguments. Decide on the evidence in the code, not on which argument sounds more confident.
- "violates": the rule as written is clearly broken at the cited (or other) lines.
- "clean": the file clearly follows the rule or the rule governs nothing.
- "ambiguous": the rule's wording genuinely supports both readings.`

// --- Sampling ---------------------------------------------------------------------------------------

const runSample = async () => {
  const targetCount = Number(opt("--count", "216"))
  const perRepo = Number(opt("--per-repo", "3"))
  const seed = Number(opt("--seed", "20261122"))

  const corpus = await loadCorpus({ requireSplits: false })
  const usedRepos = new Set<string>()
  for (const file of corpus.files) if (file.upstream) usedRepos.add(file.upstream.repo)
  const minedCand = join(import.meta.dir, ".cache/research/review/candidates.jsonl")
  if (existsSync(minedCand)) {
    for (const line of (await Bun.file(minedCand).text()).split("\n")) {
      if (line.trim()) usedRepos.add((JSON.parse(line) as { repo: string }).repo)
    }
  }

  const existing = await loadManifest()
  for (const entry of existing) usedRepos.add(entry.upstream.repo)
  const countsByLang: Record<string, number> = { go: 0, py: 0, ts: 0 }
  for (const entry of existing) countsByLang[entry.language] = (countsByLang[entry.language] ?? 0) + 1

  if (!existsSync(reposTsv)) throw new Error(`Missing candidate repo pool at ${reposTsv}`)
  const poolRows = (await Bun.file(reposTsv).text()).trim().split("\n").map((l) => l.split("\t"))
  const seen = new Set<string>()
  const pool: Array<{ lang: string; tier: string; repo: string; stars: number; desc: string }> = []
  for (const [lang, tier, repo, stars, desc = ""] of poolRows) {
    if (!lang || !tier || !repo || seen.has(repo) || usedRepos.has(repo)) continue
    if (badRepo.test(`${repo} ${desc}`)) continue
    seen.add(repo)
    pool.push({ lang, tier, repo, stars: Number(stars), desc })
  }

  // Round-robin across (lang x tier) strata so the holdout is balanced across languages and star tiers.
  const next = mulberry32(seed)
  const strata: Array<Array<(typeof pool)[number]>> = []
  for (const lang of ["go", "python", "typescript"]) {
    for (const tier of ["100..1000", "1000..20000", ">20000"]) {
      strata.push(shuffle(pool.filter((r) => r.lang === lang && r.tier === tier), next))
    }
  }
  const orderedRepos: Array<(typeof pool)[number]> = []
  let addedAny = true
  while (addedAny) {
    addedAny = false
    for (const bucket of strata) {
      const item = bucket.shift()
      if (item) {
        orderedRepos.push(item)
        addedAny = true
      }
    }
  }

  let remaining = (await $`gh api rate_limit --jq .resources.core.remaining`.json()) as number
  console.log(`GitHub API remaining: ${remaining}; unseen candidate repos: ${orderedRepos.length}; existing holdout files: ${existing.length}/${targetCount}`)

  const cachedGh = async <A>(file: string, endpoint: string, jq?: string): Promise<A | undefined> => {
    if (existsSync(file)) return (await Bun.file(file).json()) as A
    if (remaining <= 100) return undefined
    remaining--
    const res = jq ? await $`gh api ${endpoint} --jq ${jq}`.nothrow().quiet() : await $`gh api ${endpoint}`.nothrow().quiet()
    if (res.exitCode !== 0) return undefined
    const val = res.json() as A
    mkdirSync(dirname(file), { recursive: true })
    await Bun.write(file, JSON.stringify(val))
    return val
  }

  mkdirSync(filesDir, { recursive: true })
  mkdirSync(licensesDir, { recursive: true })
  const manifest = [...existing]

  for (const cand of orderedRepos) {
    if (manifest.length >= targetCount) break
    if (remaining <= 120) {
      console.log(`Stopping early to preserve GitHub rate limit (${remaining} left).`)
      break
    }
    const rawDir = join(cacheDir, "raw", cand.repo.replace("/", "__"))
    const info = await cachedGh<{ license: string | null; branch: string; stars: number; fork: boolean; archived: boolean }>(
      join(rawDir, "repo.json"),
      `repos/${cand.repo}`,
      "{license: .license.spdx_id, branch: .default_branch, stars: .stargazers_count, fork: .fork, archived: .archived}"
    )
    if (!info || !info.license || !licenses.has(info.license) || info.fork || info.archived) continue
    const head = await cachedGh<{ sha: string; date: string }>(
      join(rawDir, "head.json"),
      `repos/${cand.repo}/commits/${info.branch}`,
      "{sha: .sha, date: .commit.committer.date}"
    )
    if (!head) continue
    const tree = await cachedGh<{ entries: Array<{ path: string; type: string; size?: number }> }>(
      join(rawDir, "tree.json"),
      `repos/${cand.repo}/git/trees/${head.sha}?recursive=1`,
      "{entries: [.tree[] | {path, type, size}]}"
    )
    if (!tree) continue

    const wantLang: "go" | "py" | "ts" = cand.lang === "go" ? "go" : cand.lang === "python" ? "py" : "ts"
    const eligible = tree.entries.filter(
      (e) => e.type === "blob" && langOf(e.path) === wantLang && !excluded.test(e.path) && (e.size ?? 0) >= 400 && (e.size ?? 0) <= 50_000
    )
    if (eligible.length === 0) continue

    const rng = mulberry32(hashStr(cand.repo, seed))
    const cells = new Map<string, typeof eligible>()
    for (const e of eligible) {
      const key = `${isTestPath(e.path) ? "test" : "source"}/${sizeBin(e.size!)}`
      cells.set(key, [...(cells.get(key) ?? []), e])
    }
    for (const list of cells.values()) shuffle(list.sort((a, b) => (a.path < b.path ? -1 : 1)), rng)
    const open = (kind: string) => [...cells.keys()].sort().filter((k) => k.startsWith(kind) && cells.get(k)!.length > 0)

    // Ensure license file is saved once per repo
    const licFile = join(licensesDir, `${cand.repo.replace("/", "__")}.txt`)
    if (!existsSync(licFile)) {
      const lic = await cachedGh<{ content: string }>(join(rawDir, "license.json"), `repos/${cand.repo}/license`, "{content: .content}")
      if (!lic?.content) continue
      await Bun.write(licFile, Buffer.from(lic.content, "base64").toString("utf8"))
    }

    let picked = 0
    while (picked < perRepo && manifest.length < targetCount && (open("test").length > 0 || open("source").length > 0)) {
      const wanted = rng() < 0.3 ? "test" : "source"
      const keys = open(wanted).length > 0 ? open(wanted) : open(wanted === "test" ? "source" : "test")
      const cellKey = keys[Math.floor(rng() * keys.length)]!
      const chosen = cells.get(cellKey)!.shift()!
      const rawUrl = `https://raw.githubusercontent.com/${cand.repo}/${head.sha}/${chosen.path}`
      const resp = await fetch(rawUrl).catch(() => undefined)
      if (!resp || !resp.ok) continue
      const source = await resp.text()
      if (source.includes("\r") || source.includes("\0") || generatedMarker.test(source.slice(0, 600))) continue

      const committedRes = await cachedGh<{ date: string | null }>(
        join(rawDir, `commit-${hashStr(chosen.path, 1) >>> 0}.json`),
        `repos/${cand.repo}/commits?sha=${head.sha}&path=${encodeURIComponent(chosen.path)}&per_page=1`,
        "{date: (.[0].commit.committer.date // null)}"
      )
      const seq = (countsByLang[wantLang] ?? 0) + 1
      countsByLang[wantLang] = seq
      const id = `h${wantLang}-${String(seq).padStart(3, "0")}`
      const dest = join(filesDir, id, chosen.path)
      mkdirSync(dirname(dest), { recursive: true })
      await Bun.write(dest, source)

      const entry: ManifestEntry = {
        id,
        path: chosen.path,
        language: wantLang,
        origin: "real",
        upstream: { repo: cand.repo, commit: head.sha, path: chosen.path, license: info.license },
        provenance: {
          source: "sampled",
          committed: committedRes?.date ?? head.date,
          stratum: `${cand.lang}/${cand.tier}/${cellKey}`,
          stars: info.stars
        }
      }
      manifest.push(entry)
      picked++
      await Bun.write(manifestPath, `${manifest.map((m) => JSON.stringify(m)).join("\n")}\n`)
    }
    if (picked > 0) console.log(`  +${picked} from ${cand.repo} (${info.license}, ★${info.stars}) -> total ${manifest.length}/${targetCount}`)
  }
  console.log(`Done sampling: ${manifest.length} files in ${manifestPath} (go=${countsByLang.go}, py=${countsByLang.py}, ts=${countsByLang.ts})`)
}

// --- Labeling (H11 two-model protocol via Claude Code CLI + Codex CLI) ------------------------------

interface LabelItem {
  readonly label: "violates" | "complies" | "not-applicable"
  readonly lines: ReadonlyArray<ReadonlyArray<number>>
  readonly note: string
}
type LabelMap = Record<string, LabelItem>
interface AdjResult {
  readonly decision: "violates" | "clean" | "ambiguous"
  readonly reason: string
}

const labelSchemaOf = (policies: ReadonlyArray<string>) => ({
  type: "object",
  properties: Object.fromEntries(
    policies.map((p) => [
      slug(p),
      {
        type: "object",
        properties: {
          label: { type: "string", enum: ["violates", "complies", "not-applicable"] },
          lines: { type: "array", items: { type: "array", items: { type: "integer" } } },
          note: { type: "string" }
        },
        required: ["label", "lines", "note"],
        additionalProperties: false
      }
    ])
  ),
  required: policies.map(slug),
  additionalProperties: false
})

const adjSchema = {
  type: "object",
  properties: {
    decision: { type: "string", enum: ["violates", "clean", "ambiguous"] },
    reason: { type: "string" }
  },
  required: ["decision", "reason"],
  additionalProperties: false
}

const runClaudeJson = async <T>(system: string, prompt: string, schema: unknown, model?: string): Promise<T> => {
  const cmd = [
    "claude",
    "-p",
    "--tools",
    "",
    "--no-session-persistence",
    "--output-format",
    "json",
    "--system-prompt",
    system,
    "--json-schema",
    JSON.stringify(schema),
    ...(model ? ["--model", model] : [])
  ]
  const proc = Bun.spawn(cmd, { stdin: new Blob([prompt]), stdout: "pipe", stderr: "pipe" })
  const [stdout, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited])
  if (code !== 0) throw new Error(`claude exited ${code}: ${stderr.slice(0, 300)}`)
  const parsed = JSON.parse(stdout) as { structured_output?: T; result?: string; is_error?: boolean } | Array<{ type?: string; structured_output?: T; result?: string; is_error?: boolean }>
  const obj = Array.isArray(parsed) ? parsed.findLast((x) => x.type === "result") ?? parsed.at(-1) : parsed
  if (!obj || obj.is_error) throw new Error(`claude error: ${stdout.slice(0, 300)}`)
  if (obj.structured_output !== undefined) return obj.structured_output
  if (typeof obj.result === "string") return JSON.parse(obj.result) as T
  throw new Error(`claude returned no structured_output: ${stdout.slice(0, 300)}`)
}

const runCodexJson = async <T>(system: string, prompt: string, schema: unknown, tmpKey: string, model?: string): Promise<T> => {
  const tmpDir = join(cacheDir, "tmp")
  mkdirSync(tmpDir, { recursive: true })
  const schemaPath = join(tmpDir, `${tmpKey}.schema.json`)
  const outPath = join(tmpDir, `${tmpKey}.out.json`)
  await Bun.write(schemaPath, JSON.stringify(schema))
  const fullPrompt = `${system}\n\n${prompt}`
  const cmd = [
    "codex",
    "exec",
    "--skip-git-repo-check",
    "-s",
    "read-only",
    "--output-schema",
    schemaPath,
    "-o",
    outPath,
    ...(model ? ["-m", model] : []),
    "-"
  ]
  const proc = Bun.spawn(cmd, { stdin: new Blob([fullPrompt]), stdout: "pipe", stderr: "pipe" })
  const [, stderr, code] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text(), proc.exited])
  if (code !== 0 || !existsSync(outPath)) throw new Error(`codex exited ${code}: ${stderr.slice(0, 300)}`)
  return JSON.parse(await Bun.file(outPath).text()) as T
}

const cleanLines = (lines: ReadonlyArray<ReadonlyArray<number>>, totalLines: number): Array<[number, number]> => {
  const out: Array<[number, number]> = []
  for (const r of lines ?? []) {
    if (r.length === 1) {
      const v = Math.max(1, Math.min(totalLines, Math.trunc(r[0]!)))
      out.push([v, v])
    } else if (r.length >= 2) {
      let a = Math.trunc(r[0]!)
      let b = Math.trunc(r[1]!)
      if (a > b) [a, b] = [b, a]
      a = Math.max(1, a)
      b = Math.min(totalLines, b)
      if (a <= b) out.push([a, b])
    }
  }
  return out
}

const pooled = async <A>(items: ReadonlyArray<A>, limit: number, fn: (item: A, idx: number) => Promise<void>) => {
  let next = 0
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) {
        const i = next++
        await fn(items[i]!, i)
      }
    })
  )
}

const runLabel = async () => {
  const manifest = await loadManifest()
  if (manifest.length === 0) throw new Error(`No holdout manifest at ${manifestPath}; run --sample first`)
  const limit = Number(opt("--limit", String(manifest.length)))
  const concurrency = Number(opt("--concurrency", "4"))
  const claudeModel = opt("--claude-model", "") || undefined
  const codexModel = opt("--codex-model", "") || undefined
  const target = manifest.slice(0, limit)

  const corpus = await loadCorpus({ requireSplits: false })
  const semanticPolicies = corpus.policies.filter((p) => p.name.startsWith("semantic/"))
  const policyText = new Map(semanticPolicies.map((p) => [p.name, ruleText(p)]))
  const semanticNames = semanticPolicies.map((p) => p.name).sort()

  const claudeDir = join(cacheDir, "claude")
  const codexDir = join(cacheDir, "codex")
  const adjDir = join(cacheDir, "adj")
  mkdirSync(claudeDir, { recursive: true })
  mkdirSync(codexDir, { recursive: true })
  mkdirSync(adjDir, { recursive: true })

  const labelPrompt = (src: string, path: string, pols: ReadonlyArray<string>) => {
    const rules = pols.map((n) => `<rule id="${slug(n)}">\n${policyText.get(n)!}\n</rule>`).join("\n\n")
    return `Rules:\n\n${rules}\n\nFile \`${path}\` (line numbers prefixed):\n\n<file>\n${numbered(src)}\n</file>\n\nLabel the file against every rule above, keyed by rule id.`
  }

  // Stage 1: Independent labeling by Claude and Codex (resumable, cached per file)
  let doneC = 0
  let doneX = 0
  let errC = 0
  let errX = 0
  const t0 = performance.now()

  await Promise.all([
    pooled(target, concurrency, async (entry) => {
      const out = join(claudeDir, `${entry.id}.json`)
      if (existsSync(out)) { doneC++; return }
      const src = await Bun.file(join(filesDir, entry.id, entry.path)).text()
      const pols = matchingSemanticPolicies(entry.path, semanticNames)
      for (let attempt = 1; attempt <= 3; attempt++) {
        try {
          const res = await runClaudeJson<LabelMap>(LABELER_SYSTEM, labelPrompt(src, entry.path, pols), labelSchemaOf(pols), claudeModel)
          await Bun.write(out, JSON.stringify(res))
          doneC++
          if (doneC % 10 === 0 || doneC === target.length) {
            console.log(`Claude labels: ${doneC}/${target.length} (${((performance.now() - t0) / 1000).toFixed(0)}s, errs=${errC})`)
          }
          return
        } catch (e) {
          if (attempt === 3) { errC++; console.error(`Claude failed ${entry.id}: ${e}`) }
        }
      }
    }),
    pooled(target, concurrency, async (entry) => {
      const out = join(codexDir, `${entry.id}.json`)
      if (existsSync(out)) { doneX++; return }
      const src = await Bun.file(join(filesDir, entry.id, entry.path)).text()
      const pols = matchingSemanticPolicies(entry.path, semanticNames)
      for (let attempt = 1; attempt <= 3; attempt++) {
        try {
          const res = await runCodexJson<LabelMap>(LABELER_SYSTEM, labelPrompt(src, entry.path, pols), labelSchemaOf(pols), `codex-${entry.id}`, codexModel)
          await Bun.write(out, JSON.stringify(res))
          doneX++
          if (doneX % 10 === 0 || doneX === target.length) {
            console.log(`Codex labels:  ${doneX}/${target.length} (${((performance.now() - t0) / 1000).toFixed(0)}s, errs=${errX})`)
          }
          return
        } catch (e) {
          if (attempt === 3) { errX++; console.error(`Codex failed ${entry.id}: ${e}`) }
        }
      }
    })
  ])

  // Stage 2: Collect all violates-vs-clean disagreements and adjudicate blinded with randomized A/B order
  const disagreements: Array<{ entry: ManifestEntry; pol: string; a: LabelItem; b: LabelItem; key: string }> = []
  for (const entry of target) {
    const cPath = join(claudeDir, `${entry.id}.json`)
    const xPath = join(codexDir, `${entry.id}.json`)
    if (!existsSync(cPath) || !existsSync(xPath)) continue
    const cMap = (await Bun.file(cPath).json()) as LabelMap
    const xMap = (await Bun.file(xPath).json()) as LabelMap
    for (const pol of matchingSemanticPolicies(entry.path, semanticNames)) {
      const a = cMap[slug(pol)]
      const b = xMap[slug(pol)]
      if (!a || !b) continue
      const va = a.label === "violates"
      const vb = b.label === "violates"
      if (va !== vb) disagreements.push({ entry, pol, a, b, key: `${entry.id}__${slug(pol)}` })
    }
  }
  console.log(`Disagreements to adjudicate: ${disagreements.length}`)

  let doneA = 0
  let errA = 0
  const fmtArg = (x: LabelItem) =>
    `label: ${x.label === "violates" ? "violates" : `clean (${x.label})`}; lines: ${JSON.stringify(x.lines ?? [])}; note: ${x.note}`

  await pooled(disagreements, concurrency, async ({ entry, pol, a, b, key }) => {
    const out = join(adjDir, `${key}.json`)
    if (existsSync(out)) { doneA++; return }
    const src = await Bun.file(join(filesDir, entry.id, entry.path)).text()
    const swap = (hashStr(key, 42) & 1) === 1
    const [first, second] = swap ? [b, a] : [a, b]
    const prompt = `<rule>\n${policyText.get(pol)!}\n</rule>\n\nFile \`${entry.path}\`:\n<file>\n${numbered(src)}\n</file>\n\nReviewer A: ${fmtArg(first)}\nReviewer B: ${fmtArg(second)}\n\nDecide.`
    for (let attempt = 1; attempt <= 3; attempt++) {
      try {
        const res = await runClaudeJson<AdjResult>(ADJ_SYSTEM, prompt, adjSchema, claudeModel)
        await Bun.write(out, JSON.stringify(res))
        doneA++
        if (doneA % 25 === 0 || doneA === disagreements.length) {
          console.log(`Adjudications: ${doneA}/${disagreements.length} (${((performance.now() - t0) / 1000).toFixed(0)}s, errs=${errA})`)
        }
        return
      } catch (e) {
        if (attempt === 3) { errA++; console.error(`Adjudication failed ${key}: ${e}`) }
      }
    }
  })

  // Stage 3: Merge into holdout.jsonl (exact pipeline.py merge_case)
  const merged: Array<Record<string, unknown>> = []
  let totalViol = 0
  let totalAmb = 0
  for (const entry of target) {
    const cPath = join(claudeDir, `${entry.id}.json`)
    const xPath = join(codexDir, `${entry.id}.json`)
    if (!existsSync(cPath) || !existsSync(xPath)) continue
    const cMap = (await Bun.file(cPath).json()) as LabelMap
    const xMap = (await Bun.file(xPath).json()) as LabelMap
    const src = await Bun.file(join(filesDir, entry.id, entry.path)).text()
    const totalLines = src.split("\n").length
    const labels: Record<string, { label: string; lines?: Array<[number, number]>; note: string }> = {}
    let complete = true
    for (const pol of matchingSemanticPolicies(entry.path, semanticNames)) {
      const a = cMap[slug(pol)]
      const b = xMap[slug(pol)]
      if (!a || !b) { complete = false; break }
      const va = a.label === "violates"
      const vb = b.label === "violates"
      const goldFrom = (x: LabelItem) => {
        if (x.label !== "violates") return { label: x.label, note: x.note }
        const lines = cleanLines(x.lines, totalLines)
        return lines.length > 0 ? { label: "violates", lines, note: x.note } : undefined
      }
      if (va === vb) {
        const g = goldFrom(a) ?? goldFrom(b)
        labels[pol] = g ?? { label: "ambiguous", note: `Both flagged violation without valid lines. ${a.note}` }
      } else {
        const adjPath = join(adjDir, `${entry.id}__${slug(pol)}.json`)
        if (!existsSync(adjPath)) { complete = false; break }
        const adj = (await Bun.file(adjPath).json()) as AdjResult
        if (adj.decision === "violates") {
          const flagging = va ? a : b
          const g = goldFrom(flagging)
          labels[pol] = g ?? { label: "ambiguous", note: `Adjudicated violates without valid lines. ${adj.reason}` }
        } else if (adj.decision === "clean") {
          const clean = !va ? a : b
          labels[pol] = { label: clean.label, note: clean.note }
        } else {
          const [v, c] = va ? [a, b] : [b, a]
          labels[pol] = { label: "ambiguous", note: `${adj.reason} Violates reading: ${v.note} Complies reading: ${c.note}` }
        }
      }
      if (labels[pol]!.label === "violates") totalViol++
      if (labels[pol]!.label === "ambiguous") totalAmb++
    }
    if (complete) {
      merged.push({
        id: entry.id,
        path: entry.path,
        split: "test",
        origin: "real",
        upstream: entry.upstream,
        provenance: entry.provenance,
        labels
      })
    }
  }
  await Bun.write(labeledPath, `${merged.map((m) => JSON.stringify(m)).join("\n")}\n`)
  console.log(`\nWrote ${merged.length} fully labeled holdout files to ${labeledPath} (${totalViol} clear violations, ${totalAmb} ambiguous).`)
}

const runStatus = async () => {
  const manifest = await loadManifest()
  const cCount = manifest.filter((e) => existsSync(join(cacheDir, "claude", `${e.id}.json`))).length
  const xCount = manifest.filter((e) => existsSync(join(cacheDir, "codex", `${e.id}.json`))).length
  const labeled = existsSync(labeledPath)
    ? (await Bun.file(labeledPath).text()).trim().split("\n").filter(Boolean).map((l) => JSON.parse(l) as { labels: Record<string, { label: string }> })
    : []
  console.log(`Holdout status: sampled=${manifest.length}, claude=${cCount}, codex=${xCount}, merged=${labeled.length}`)
  if (labeled.length > 0) {
    const byPol = new Map<string, { v: number; c: number; a: number }>()
    for (const row of labeled) {
      for (const [pol, g] of Object.entries(row.labels)) {
        const s = byPol.get(pol) ?? { v: 0, c: 0, a: 0 }
        if (g.label === "violates") s.v++
        else if (g.label === "ambiguous") s.a++
        else s.c++
        byPol.set(pol, s)
      }
    }
    for (const [pol, s] of [...byPol.entries()].sort()) {
      console.log(`  ${pol.replace("semantic/", "").padEnd(42)} viol=${String(s.v).padStart(3)} clean=${String(s.c).padStart(3)} amb=${String(s.a).padStart(3)}`)
    }
  }
}

